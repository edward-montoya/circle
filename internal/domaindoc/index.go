package domaindoc

import (
	"bytes"
	"fmt"
	"os"
	"path/filepath"
	"strings"
)

// IndexPath is where the index lives: .circle/DOMAIN-INDEX.md.
func IndexPath(root string) string { return filepath.Join(root, ".circle", IndexName) }

// Render writes the index.
//
// Deterministic on purpose — no timestamp, stable order — so "is the index
// current?" is a byte comparison, and an index that did not change produces no
// diff to commit.
func Render(m Model) string {
	var b strings.Builder
	b.WriteString("# Domain index\n\n")
	b.WriteString("<!-- Generated by `circle domain index`. Do not edit: change a DOMAIN.md, an ADR\n")
	b.WriteString("     or an architecture document, and Circle regenerates this file. -->\n\n")

	undocumented := 0
	for _, mo := range m.Modules {
		if mo.By == "" {
			undocumented++
		}
	}
	fmt.Fprintf(&b, "%d domain(s) · %d ADR(s) · %d architecture doc(s) · %d module(s), %d undocumented\n\n",
		len(m.Domains), len(m.ADRs), len(m.Architecture), len(m.Modules), undocumented)

	b.WriteString("## Domains\n\n")
	if len(m.Domains) == 0 {
		b.WriteString("_None yet. Every concept the code introduces belongs in a `DOMAIN.md`; create the first\n")
		b.WriteString("one in the directory it covers, or at the root for the whole repository._\n\n")
	} else {
		b.WriteString("| Domain | File | Covers | Terms |\n|---|---|---|---|\n")
		for _, d := range m.Domains {
			scope := d.Scope + "/"
			if d.Scope == "" {
				scope = "whole repository"
			}
			fmt.Fprintf(&b, "| **%s** | [`%s`](../%s) | `%s` | %d |\n", d.Name, d.Path, d.Path, scope, len(d.Terms))
		}
		b.WriteString("\n")
		for _, d := range m.Domains {
			if len(d.Terms) == 0 {
				continue
			}
			fmt.Fprintf(&b, "### %s\n\n", d.Name)
			for _, t := range d.Terms {
				fmt.Fprintf(&b, "- **%s**", t.Name)
				if len(t.Avoid) > 0 {
					fmt.Fprintf(&b, " — _avoid_: %s", strings.Join(t.Avoid, ", "))
				}
				b.WriteString("\n")
			}
			b.WriteString("\n")
		}
	}

	b.WriteString("## Decisions\n\n")
	if len(m.ADRs) == 0 {
		b.WriteString("_No ADRs yet._\n\n")
	} else {
		b.WriteString("| # | Decision | Status | Domain |\n|---|---|---|---|\n")
		for _, a := range m.ADRs {
			dom := a.Domain
			if dom == "" {
				dom = "system"
			}
			fmt.Fprintf(&b, "| %s | [%s](../%s) | %s | %s |\n", a.Number, a.Title, a.Path, orDash(a.Status), dom)
		}
		b.WriteString("\n")
	}

	b.WriteString("## Architecture\n\n")
	if len(m.Architecture) == 0 {
		b.WriteString("_No architecture documents yet._\n\n")
	} else {
		for _, a := range m.Architecture {
			fmt.Fprintf(&b, "- [%s](../%s)\n", a.Title, a.Path)
		}
		b.WriteString("\n")
	}

	b.WriteString("## Modules\n\n")
	if len(m.Modules) == 0 {
		b.WriteString("_No source modules found._\n")
	} else {
		b.WriteString("| Module | Domain | Documented by |\n|---|---|---|\n")
		for _, mo := range m.Modules {
			by := "⚠ **undocumented**"
			if mo.By != "" {
				by = "`" + mo.By + "`"
			}
			fmt.Fprintf(&b, "| `%s/` | %s | %s |\n", mo.Path, orDash(mo.Domain), by)
		}
	}
	return b.String()
}

func orDash(s string) string {
	if s == "" {
		return "—"
	}
	return s
}

// Sync regenerates the index and reports whether it changed.
func Sync(root string) (Model, bool, error) {
	m := Discover(root)
	want := []byte(Render(m))
	have, err := os.ReadFile(IndexPath(root))
	if err == nil && bytes.Equal(have, want) {
		return m, false, nil
	}
	if err := os.MkdirAll(filepath.Dir(IndexPath(root)), 0o755); err != nil {
		return m, false, err
	}
	return m, true, os.WriteFile(IndexPath(root), want, 0o644)
}

// Fresh reports whether the index on disk matches the repository.
func Fresh(root string) (Model, bool) {
	m := Discover(root)
	have, err := os.ReadFile(IndexPath(root))
	return m, err == nil && string(have) == Render(m)
}
